"""One-off backfill: retry every already-committed term's invalid findings against a local model.

local_llm_review_loop.py's retry step (see its retry_issues()) only catches invalid responses
from the round that just ran -- terms reviewed before that retry step existed (or reviewed in a
round where a different accession happened to fail) are permanent dead ends otherwise, since
plan_review_round.py never revisits an already-started term. This script scans every term
directory already under experiments/mf_span/llm_term_review/ for parsed_findings.json issues that are
genuinely invalid (unresolved pointer, malformed verdict, wrong go_id -- not a decisive NONE,
which is a real answer, not garbled data), and gives each one an extra shot, reusing the exact
same call/parse/retry/merge logic from local_llm_review_loop.py.

Usage:
  python3 experiments/ancestor_sweep/scripts/backfill_retry_issues.py --host http://192.168.1.122:1234
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import local_llm_review_loop as loop

ROOT = loop.ROOT
SCRIPTS = loop.SCRIPTS


def find_terms_with_retryable_issues():
  terms = []
  for term_dir in sorted(ROOT.iterdir()):
    if not term_dir.is_dir():
      continue
    parsed_path = term_dir / "parsed_findings.json"
    if not parsed_path.exists():
      continue
    parsed = json.loads(parsed_path.read_text())
    if any(i.get("reason") in loop.RETRYABLE_ISSUE_REASONS for i in parsed.get("issues", [])):
      terms.append(term_dir.name.replace("_", ":", 1))
  return terms


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--host", required=True, help="LM Studio server, e.g. http://192.168.1.122:1234")
  ap.add_argument("--model", default=None, help="Model id; auto-detected from /v1/models if omitted")
  ap.add_argument("--request-timeout", type=int, default=180)
  ap.add_argument("--chain-of-thought", type=str, default="",
                   help="Same flag as local_llm_review_loop.py -- should match whatever the "
                        "original rounds used, for consistent behavior.")
  ap.add_argument("--max-tokens", type=int, default=1536)
  args = ap.parse_args()

  model = args.model or loop.discover_model(args.host)
  system_prompt = loop.build_system_prompt(args.chain_of_thought)
  print(f"Using model: {model} @ {args.host}"
        + (" (chain-of-thought enabled)" if args.chain_of_thought else ""))

  terms = find_terms_with_retryable_issues()
  if not terms:
    print("No terms with retryable issues found -- nothing to backfill.")
    return
  print(f"Found {len(terms)} term(s) with retryable issues: {', '.join(terms)}")

  merged_terms = []
  total_retried = 0
  for go_id in terms:
    n = loop.retry_issues(args.host, model, system_prompt, go_id, args.request_timeout,
                           args.max_tokens)
    if n == 0:
      continue
    total_retried += n
    loop.run([sys.executable, str(SCRIPTS / "parse_llm_findings.py"), go_id])
    result = subprocess.run(
        [sys.executable, str(SCRIPTS / "merge_llm_findings.py"), go_id],
        check=True, capture_output=True, text=True)
    print(result.stdout, end="")
    if re.match(rf"^{re.escape(go_id)}: merged [1-9]", result.stdout):
      merged_terms.append(go_id)

  if total_retried == 0:
    print("Issues were logged but retry_issues() found nothing retryable -- nothing to do.")
    return

  loop.run([sys.executable, str(SCRIPTS / "build_positional_mf_links.py")])

  loop.run(["git", "add", "experiments/mf_span/llm_term_review/", "experiments/mf_span/positional_mf_gaps.json",
            "experiments/mf_span/positional_mf_links.json", "experiments/mf_span/positional_mf_llm_review_log.json",
            "experiments/mf_span/positional_mf_localization_dictionary.json",
            "experiments/mf_span/positional_mf_spotcheck_sample.json"])
  status = subprocess.run(["git", "diff", "--cached", "--quiet"])
  if status.returncode == 0:
    print("(nothing to commit)")
    return
  merged_line = ", ".join(merged_terms) if merged_terms else "none"
  msg = (
      f"fix: backfill-retry {total_retried} invalid finding(s) across {len(terms)} term(s), "
      f"merged: {merged_line}\n\n"
      f"Generated by backfill_retry_issues.py against a local LM Studio model.\n"
      f"Retried: {total_retried} finding(s). Merged: {merged_line}."
  )
  loop.run(["git", "commit", "-m", msg])
  print(f"Done. Retried {total_retried} finding(s) across {len(terms)} term(s). "
        f"Merged: {merged_line}")


if __name__ == "__main__":
  main()
