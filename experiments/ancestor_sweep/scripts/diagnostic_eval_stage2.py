"""Post-hoc diagnostic for a checkpoint that was trained WITHOUT --run-diagnostic (e.g.
trial-071/trial-072, trained before that flag existed) - re-downloads the checkpoint
from the Hub and calls training_run.run_diagnostic() against it. For any trial run
through a notebook generated by build_notebook.py going forward, --run-diagnostic is
appended automatically and this whole re-download-and-reload step is unnecessary - the
diagnostic already ran against the in-memory model right after training, on whatever
GPU it trained on (this script has no GPU access in this sandbox and runs on CPU only,
which is dramatically slower for anything above ~100M params - see run_diagnostic()'s
own docstring in training_run.py for why the diagnostic itself exists).

Meant to run directly via `python3 experiments/ancestor_sweep/scripts/diagnostic_eval_stage2.py <revision> [max_val_samples]`,
not through Colab, since it doesn't need training_run.py's Colab-secrets HF token path
(local huggingface_hub cache already has one).
"""

import json
import sys
from functools import partial
from pathlib import Path

import torch
from huggingface_hub import hf_hub_download

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
import training_run

CHECKPOINT_REVISION = sys.argv[1] if len(sys.argv) > 1 else "trial-050"
HF_REPO_ID = "kelmoir/cafa6-esm"
MAX_VAL_SAMPLES = int(sys.argv[2]) if len(sys.argv) > 2 else 2000

# push_checkpoint() (training_run.py) writes trial_metrics.json alongside every
# checkpoint with the full CLI config for that trial (model_name, use_lora, etc.) - read
# it back instead of hardcoding model_name/use_lora here, so this script works
# unmodified for any future trial (e.g. a --use-lora esm2_t36_3B run), not just the
# esm2_t12_35M non-LoRA trials it was originally written against.
trial_metrics_path = hf_hub_download(repo_id=HF_REPO_ID, filename="trial_metrics.json", revision=CHECKPOINT_REVISION)
trial_config = json.loads(Path(trial_metrics_path).read_text())["config"]
MODEL_NAME = trial_config["model_name"]
USE_LORA = trial_config.get("use_lora", False)
MIXED_PRECISION = trial_config.get("mixed_precision", "no")
AUTOCAST_DTYPE = {"fp16": torch.float16, "bf16": torch.bfloat16}.get(MIXED_PRECISION)

dataset = training_run.load_training_data(data_path=Path("data/cafa-6-protein-function-prediction/dataset"))
label_names = [str(name) for name in dataset["train"].features["labels"].feature.names]
id2label = {i: name for i, name in enumerate(label_names)}
label2id = {name: i for i, name in id2label.items()}

tokenizer = training_run.create_esm_tokenizer(MODEL_NAME)
preprocess = partial(
    training_run.preprocess_batch,
    tokenizer=tokenizer,
    max_length=training_run.MAX_LENGTH,
    unique_items=label_names,
    label2id=label2id,
)

val_ds = dataset["validation"].with_transform(transform=preprocess)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
use_amp = AUTOCAST_DTYPE is not None and device.type == "cuda"
if USE_LORA:
    # A LoRA checkpoint on HF_REPO_ID is adapter-only, not a full standalone model - the
    # base architecture must load fresh from MODEL_NAME, with the adapter weights
    # attached separately via lora_resume_repo_id. PeftModel.from_pretrained reads the
    # adapter's own saved adapter_config.json (rank/alpha/target_modules) rather than
    # anything passed here, so lora_r/lora_alpha/etc. don't need to be reconstructed.
    # lora_base_dtype must match how the checkpoint was trained (e.g. bf16) - if the
    # frozen backbone loads in a different dtype than the trainable classifier/adapters
    # (which peft/create_esm always keep fp32), any forward pass run outside an autocast
    # region raises "mat1 and mat2 must have the same dtype" - only training_run.py's own
    # training loop wraps every forward pass in autocast, so this script needs the same
    # treatment for its own inference-only forward passes below.
    model = training_run.create_esm(
        model_type=MODEL_NAME,
        use_lora=True,
        lora_resume_repo_id=HF_REPO_ID,
        revision=CHECKPOINT_REVISION,
        id2label=id2label,
        label2id=label2id,
        lora_base_dtype=AUTOCAST_DTYPE,
    ).to(device)
else:
    model = training_run.create_esm(
        unfreeze_last_n=1,
        model_type=HF_REPO_ID,
        revision=CHECKPOINT_REVISION,
        id2label=id2label,
        label2id=label2id,
    ).to(device)
model.eval()
print(f"[INFO] Loaded {HF_REPO_ID}@{CHECKPOINT_REVISION} ({MODEL_NAME}, use_lora={USE_LORA}) for eval, device={device}")

training_run.run_diagnostic(
    model,
    tokenizer,
    val_ds,
    label_names,
    device,
    autocast_dtype=AUTOCAST_DTYPE,
    use_amp=use_amp,
    max_val_samples=MAX_VAL_SAMPLES,
    batch_size=16,
)
